-- Mission 20: persistent per-user chat data.
-- Apply once to the intended Supabase project after reviewing this migration.
-- No existing Qdrant data or user records are changed by this migration.

begin;

create table if not exists public.conversations (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null,
    title text not null default 'Nouvelle conversation',
    is_archived boolean not null default false,
    is_favorite boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint conversations_title_length check (
        char_length(btrim(title)) between 1 and 120
    ),
    constraint conversations_user_id_fkey
        foreign key (user_id) references auth.users (id) on delete cascade,
    constraint conversations_id_user_id_unique unique (id, user_id)
);

create index if not exists conversations_owner_recent_idx
    on public.conversations (user_id, updated_at desc, id desc);
create index if not exists conversations_owner_archived_recent_idx
    on public.conversations (user_id, is_archived, updated_at desc, id desc);
create index if not exists conversations_owner_favorites_idx
    on public.conversations (user_id, is_favorite, updated_at desc, id desc);

create table if not exists public.messages (
    id uuid primary key default gen_random_uuid(),
    conversation_id uuid not null,
    user_id uuid not null references auth.users (id) on delete cascade,
    role text not null,
    content text not null,
    sources jsonb not null default '[]'::jsonb,
    images jsonb not null default '[]'::jsonb,
    client_request_id uuid,
    sequence_number bigint generated by default as identity,
    created_at timestamptz not null default now(),
    constraint messages_conversation_owner_fk
        foreign key (conversation_id, user_id)
        references public.conversations (id, user_id)
        on delete cascade,
    constraint messages_role_check check (role in ('user', 'assistant')),
    constraint messages_content_length check (
        char_length(btrim(content)) between 1 and 24000
    ),
    constraint messages_sources_array check (jsonb_typeof(sources) = 'array'),
    constraint messages_images_array check (jsonb_typeof(images) = 'array'),
    constraint messages_sequence_unique unique (conversation_id, sequence_number),
    constraint messages_idempotency_unique
        unique (conversation_id, client_request_id, role)
);

-- IF NOT EXISTS does not reconcile a pre-existing table. Fail closed if either
-- object lacks the columns, types, nullability, or named constraints below.
do $$
declare
    expected record;
begin
    for expected in
        select * from (values
            ('conversations', 'id', 'uuid', 'NO'),
            ('conversations', 'user_id', 'uuid', 'NO'),
            ('conversations', 'title', 'text', 'NO'),
            ('conversations', 'is_archived', 'boolean', 'NO'),
            ('conversations', 'is_favorite', 'boolean', 'NO'),
            ('conversations', 'created_at', 'timestamp with time zone', 'NO'),
            ('conversations', 'updated_at', 'timestamp with time zone', 'NO'),
            ('messages', 'id', 'uuid', 'NO'),
            ('messages', 'conversation_id', 'uuid', 'NO'),
            ('messages', 'user_id', 'uuid', 'NO'),
            ('messages', 'role', 'text', 'NO'),
            ('messages', 'content', 'text', 'NO'),
            ('messages', 'sources', 'jsonb', 'NO'),
            ('messages', 'images', 'jsonb', 'NO'),
            ('messages', 'client_request_id', 'uuid', 'YES'),
            ('messages', 'sequence_number', 'bigint', 'NO'),
            ('messages', 'created_at', 'timestamp with time zone', 'NO')
        ) as required(table_name, column_name, data_type, is_nullable)
    loop
        if not exists (
            select 1 from information_schema.columns c
             where c.table_schema = 'public'
               and c.table_name = expected.table_name
               and c.column_name = expected.column_name
               and c.data_type = expected.data_type
               and c.is_nullable = expected.is_nullable
        ) then
            raise exception 'Mission 20 schema mismatch: public.%.% is missing',
                expected.table_name, expected.column_name;
        end if;
    end loop;

    for expected in
        select * from (values
            ('conversations', 'conversations_pkey', 'p'),
            ('conversations', 'conversations_title_length', 'c'),
            ('conversations', 'conversations_user_id_fkey', 'f'),
            ('conversations', 'conversations_id_user_id_unique', 'u'),
            ('messages', 'messages_pkey', 'p'),
            ('messages', 'messages_conversation_owner_fk', 'f'),
            ('messages', 'messages_role_check', 'c'),
            ('messages', 'messages_content_length', 'c'),
            ('messages', 'messages_sources_array', 'c'),
            ('messages', 'messages_images_array', 'c'),
            ('messages', 'messages_sequence_unique', 'u'),
            ('messages', 'messages_idempotency_unique', 'u')
        ) as required(table_name, constraint_name, constraint_type)
    loop
        if not exists (
            select 1 from pg_constraint pc
            join pg_class t on t.oid = pc.conrelid
            join pg_namespace n on n.oid = t.relnamespace
             where n.nspname = 'public'
               and t.relname = expected.table_name
               and pc.conname = expected.constraint_name
               and pc.contype = expected.constraint_type
        ) then
            raise exception 'Mission 20 schema mismatch: constraint % is missing',
                expected.constraint_name;
        end if;
    end loop;

    if pg_get_serial_sequence('public.messages', 'sequence_number') is null then
        raise exception 'Mission 20 schema mismatch: messages.sequence_number is not identity-backed';
    end if;
    if not exists (
        select 1 from information_schema.columns c
         where c.table_schema = 'public'
           and c.table_name = 'messages'
           and c.column_name = 'sequence_number'
           and c.is_identity = 'YES'
    ) then
        raise exception 'Mission 20 schema mismatch: messages.sequence_number is not an identity column';
    end if;
end;
$$;

create index if not exists messages_conversation_order_idx
    on public.messages (conversation_id, sequence_number asc, id asc);
create index if not exists messages_owner_recent_idx
    on public.messages (user_id, created_at desc, sequence_number desc);

create or replace function public.set_conversation_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

-- A message insert changes activity even when the client cannot UPDATE the
-- parent conversation. This narrowly scoped trigger writes only that parent's
-- timestamp. The function is not callable as an API function by client roles.
create or replace function public.touch_conversation_after_message_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    update public.conversations
       set updated_at = now()
     where id = new.conversation_id
       and user_id = new.user_id;
    return new;
end;
$$;

revoke all on function public.set_conversation_updated_at()
    from public, anon, authenticated, service_role;
revoke all on function public.touch_conversation_after_message_insert()
    from public, anon, authenticated, service_role;

drop trigger if exists conversations_set_updated_at on public.conversations;
create trigger conversations_set_updated_at
before update on public.conversations
for each row execute function public.set_conversation_updated_at();

drop trigger if exists messages_touch_conversation on public.messages;
create trigger messages_touch_conversation
after insert on public.messages
for each row execute function public.touch_conversation_after_message_insert();

alter table public.conversations enable row level security;
alter table public.messages enable row level security;

-- On re-run, replace every policy on these dedicated tables. PostgreSQL
-- combines permissive policies with OR, so leaving an unknown permissive
-- policy in place could defeat the owner checks below.
do $$
declare
    existing_policy record;
begin
    for existing_policy in
        select schemaname, tablename, policyname
          from pg_policies
         where schemaname = 'public'
           and tablename in ('conversations', 'messages')
    loop
        execute format(
            'drop policy %I on %I.%I',
            existing_policy.policyname,
            existing_policy.schemaname,
            existing_policy.tablename
        );
    end loop;
end;
$$;

drop policy if exists conversations_select_owner on public.conversations;
create policy conversations_select_owner
on public.conversations for select to authenticated
using (user_id = (select auth.uid()));

drop policy if exists conversations_insert_owner on public.conversations;
create policy conversations_insert_owner
on public.conversations for insert to authenticated
with check (user_id = (select auth.uid()));

drop policy if exists conversations_update_owner on public.conversations;
create policy conversations_update_owner
on public.conversations for update to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

drop policy if exists conversations_delete_owner on public.conversations;
create policy conversations_delete_owner
on public.conversations for delete to authenticated
using (user_id = (select auth.uid()));

drop policy if exists messages_select_owner on public.messages;
create policy messages_select_owner
on public.messages for select to authenticated
using (
    user_id = (select auth.uid())
    and exists (
        select 1 from public.conversations c
        where c.id = messages.conversation_id
          and c.user_id = (select auth.uid())
    )
);

drop policy if exists messages_insert_user_only on public.messages;
create policy messages_insert_user_only
on public.messages for insert to authenticated
with check (
    role = 'user'
    and user_id = (select auth.uid())
    and exists (
        select 1 from public.conversations c
        where c.id = messages.conversation_id
          and c.user_id = (select auth.uid())
    )
);

-- Client edits are intentionally denied; corrections/regeneration require a
-- separate authenticated backend operation with ownership checks.
drop policy if exists messages_update_denied on public.messages;
create policy messages_update_denied
on public.messages for update to authenticated
using (false)
with check (false);

-- Remove table and column grants that might have been inherited from project
-- defaults or left by an earlier draft before granting the client minimum.
grant usage on schema public to authenticated, service_role;
revoke all on public.conversations, public.messages
    from public, anon, authenticated, service_role;
revoke all (id, user_id, title, is_archived, is_favorite, created_at, updated_at)
    on table public.conversations from public, anon, authenticated, service_role;
revoke all (id, conversation_id, user_id, role, content, sources, images,
    client_request_id, sequence_number, created_at)
    on table public.messages from public, anon, authenticated, service_role;

-- Column grants prevent changing ownership or timestamps. Assistant insertions
-- are reserved to FastAPI's server-only service role after JWT/ownership checks.
grant select, delete on public.conversations to authenticated;
grant insert (user_id, title) on public.conversations to authenticated;
grant update (title, is_archived, is_favorite)
    on public.conversations to authenticated;
grant select on public.messages to authenticated;
grant insert (conversation_id, user_id, role, content, client_request_id)
    on public.messages to authenticated;
revoke all on sequence public.messages_sequence_number_seq
    from public, anon, authenticated, service_role;
grant usage on sequence public.messages_sequence_number_seq
    to authenticated, service_role;
grant select on public.conversations, public.messages to service_role;
grant update (title, updated_at) on public.conversations to service_role;
grant insert (conversation_id, user_id, role, content, sources, images,
    client_request_id) on public.messages to service_role;

create or replace view public.conversation_summaries
with (security_invoker = true)
as
select
    c.id,
    c.user_id,
    c.title,
    c.is_archived,
    c.is_favorite,
    c.created_at,
    c.updated_at,
    count(m.id)::bigint as message_count,
    (array_agg(m.content order by m.sequence_number desc)
        filter (where m.id is not null))[1] as last_message,
    string_agg(m.content, ' ' order by m.sequence_number asc) as search_text
from public.conversations c
left join public.messages m
    on m.conversation_id = c.id and m.user_id = c.user_id
group by c.id;

revoke all on public.conversation_summaries
    from public, anon, authenticated, service_role;
revoke all (id, user_id, title, is_archived, is_favorite, created_at,
    updated_at, message_count, last_message, search_text)
    on table public.conversation_summaries
    from public, anon, authenticated, service_role;
grant select on public.conversation_summaries to authenticated;

create or replace function public.get_my_dashboard_stats()
returns table (
    conversation_count bigint,
    message_count bigint,
    favorite_count bigint,
    last_activity timestamptz
)
language sql
stable
security invoker
set search_path = ''
as $$
    select
        (select count(*) from public.conversations c
            where c.user_id = (select auth.uid())),
        (select count(*) from public.messages m
            where m.user_id = (select auth.uid())),
        (select count(*) from public.conversations c
            where c.user_id = (select auth.uid()) and c.is_favorite),
        (select max(c.updated_at) from public.conversations c
            where c.user_id = (select auth.uid()));
$$;

revoke all on function public.get_my_dashboard_stats()
    from public, anon, authenticated, service_role;
grant execute on function public.get_my_dashboard_stats() to authenticated;

commit;
